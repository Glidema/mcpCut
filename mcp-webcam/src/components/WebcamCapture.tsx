import { useRef, useState, useEffect, useCallback, useMemo } from "react";
import Webcam from "react-webcam";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardFooter,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Input } from "@/components/ui/input";
import { Checkbox } from "@/components/ui/checkbox";
import { captureScreen } from "@/utils/screenCapture";
import {
  buildRecordStream,
  startMediaRecorder,
  stopMediaRecorder,
  type ActiveRecorder,
} from "@/utils/webcamRecorder";
import { Github, Info, Link2, Users, Copy, Check, Circle } from "lucide-react";
import { Badge } from "@/components/ui/badge";

interface Session {
  id: string;
  connectedAt: string;
  lastActivity: string;
  isStale: boolean;
  capabilities: {
    sampling: boolean;
    tools: boolean;
    resources: boolean;
  };
  clientInfo?: {
    name: string;
    version: string;
  };
}

export function WebcamCapture() {
  const [webcamInstance, setWebcamInstance] = useState<Webcam | null>(null);
  const webcamRef = useRef<Webcam | null>(null);
  const clientIdRef = useRef<string | null>(null);
  const [_, setClientId] = useState<string | null>(null);
  const activeRecorderRef = useRef<ActiveRecorder | null>(null);
  const [isRecording, setIsRecording] = useState(false);
  const [recordingElapsed, setRecordingElapsed] = useState(0);
  const [lastRecordingPath, setLastRecordingPath] = useState<string | null>(null);
  const [recordingError, setRecordingError] = useState<string | null>(null);
  const [isSavingRecording, setIsSavingRecording] = useState(false);
  const [isStartingRecording, setIsStartingRecording] = useState(false);

  // State for configuration
  const [config, setConfig] = useState<{
    mcpHostConfigured: boolean;
    mcpHost: string;
    recordingsDir?: string;
  } | null>(null);
  
  // State for copy functionality
  const [copied, setCopied] = useState(false);

  // Copy to clipboard function
  const copyToClipboard = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy:', err);
    }
  };

  // Generate random 5-character user ID if none provided and in multiuser mode
  const generateUserId = () => {
    return Math.random().toString(36).substring(2, 7).toLowerCase();
  };

  // Validate and sanitize user ID
  const validateUserId = (userId: string): string => {
    if (!userId) return 'default';
    
    // Remove any non-alphanumeric characters and hyphens/underscores
    const sanitized = userId.replace(/[^a-zA-Z0-9_-]/g, '');
    
    // Limit to 30 characters max
    const truncated = sanitized.substring(0, 30);
    
    // If empty after sanitization, return default
    return truncated || 'default';
  };

  // Extract user parameter from URL
  const urlUserParam = new URLSearchParams(window.location.search).get('user');
  const userParam = useMemo(() => {
    if (urlUserParam) {
      return validateUserId(urlUserParam);
    }
    // Only generate random ID in multiuser mode (when MCP_HOST is configured)
    if (config?.mcpHostConfigured) {
      // Store in sessionStorage to persist across refreshes
      const storageKey = 'mcp-webcam-user-id';
      let storedUserId = sessionStorage.getItem(storageKey);
      
      if (!storedUserId) {
        storedUserId = generateUserId();
        sessionStorage.setItem(storageKey, storedUserId);
      }
      
      return validateUserId(storedUserId);
    }
    
    return 'default';
  }, [urlUserParam, config?.mcpHostConfigured]);
  
  // Determine if we should show the banner (when MCP_HOST is explicitly set)
  const showBanner = config?.mcpHostConfigured || false;

  // Update URL when user param changes (for autogenerated IDs)
  useEffect(() => {
    // Only update URL if we don't already have a user param in URL and we have a non-default userParam
    if (!urlUserParam && userParam !== 'default' && config?.mcpHostConfigured) {
      const url = new URL(window.location.href);
      url.searchParams.set('user', userParam);
      
      // Use replaceState to avoid adding to browser history
      window.history.replaceState({}, '', url.toString());
    }
  }, [userParam, urlUserParam, config?.mcpHostConfigured]);

  const [devices, setDevices] = useState<MediaDeviceInfo[]>([]);
  const [selectedDevice, setSelectedDevice] = useState<string>("default");
  const [frozenFrame, setFrozenFrame] = useState<string | null>(null);

  // New state for sampling results
  const [samplingResult, setSamplingResult] = useState<string | null>(null);
  const [samplingError, setSamplingError] = useState<string | null>(null);
  const [isSampling, setIsSampling] = useState(false);

  // State for sampling prompt and auto-update
  const [samplingPrompt, setSamplingPrompt] =
    useState<string>("你能看到什么？");
  const [autoUpdate, setAutoUpdate] = useState<boolean>(false); // Explicitly false
  const [updateInterval, setUpdateInterval] = useState<number>(30);
  const autoUpdateIntervalRef = useRef<NodeJS.Timeout | null>(null);

  // State for session management
  const [sessions, setSessions] = useState<Session[]>([]);
  const [selectedSessionId, setSelectedSessionId] = useState<string | null>(
    null
  );
  const sessionPollIntervalRef = useRef<NodeJS.Timeout | null>(null);

  // Get the currently selected session
  const selectedSession = sessions.find((s) => s.id === selectedSessionId);

  const setWebcam = useCallback((webcam: Webcam | null) => {
    webcamRef.current = webcam;
    setWebcamInstance(webcam);
  }, []);

  const getImage = useCallback(() => {
    console.log("getImage called, frozenFrame state:", frozenFrame);
    if (frozenFrame) {
      console.log("Using frozen frame");
      return frozenFrame;
    }
    console.log("Getting live screenshot");
    const screenshot = webcamRef.current?.getScreenshot() ?? webcamInstance?.getScreenshot();
    return screenshot || null;
  }, [frozenFrame, webcamInstance]);

  const uploadRecordingBlob = useCallback(
    async (active: ActiveRecorder, blob: Blob) => {
      const durationSec = (Date.now() - active.startedAt) / 1000;
      const form = new FormData();
      form.append("recordingId", active.recordingId);
      form.append("durationSec", String(durationSec));
      form.append("mimeType", blob.type || active.mimeType || "video/webm");
      form.append("file", blob, `${active.recordingId}.webm`);

      const response = await fetch(
        `/api/recording-result?user=${encodeURIComponent(userParam)}`,
        { method: "POST", body: form }
      );
      const data = await response.json();
      if (!response.ok) {
        throw new Error(data.error || "保存录像失败");
      }
      setLastRecordingPath(data.path ?? null);
      return data;
    },
    [userParam]
  );

  const discardLocalRecorder = useCallback(() => {
    const active = activeRecorderRef.current;
    if (!active) return;
    try {
      if (active.recorder.state !== "inactive") {
        active.recorder.ondataavailable = null;
        active.recorder.onstop = null;
        active.recorder.stop();
      }
    } catch {
      // ignore
    }
    activeRecorderRef.current = null;
    setIsRecording(false);
    setIsSavingRecording(false);
  }, []);

  const beginBrowserRecording = useCallback(
    async (recordingId: string, withAudio: boolean) => {
      setRecordingError(null);
      // New start always wins over a half-dead local recorder
      discardLocalRecorder();
      try {
        const videoEl = webcamRef.current?.video;
        const stream = buildRecordStream(videoEl, withAudio);
        const active = startMediaRecorder(stream, recordingId);
        activeRecorderRef.current = active;
        setIsRecording(true);
        setRecordingElapsed(0);
        await fetch(`/api/recording-started?user=${encodeURIComponent(userParam)}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ recordingId, clientId: clientIdRef.current }),
        });
      } catch (err) {
        activeRecorderRef.current = null;
        setIsRecording(false);
        const message = (err as Error).message || "开始录制失败";
        setRecordingError(message);
        await fetch(`/api/recording-start-error?user=${encodeURIComponent(userParam)}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            recordingId,
            error: { message },
          }),
        });
      }
    },
    [discardLocalRecorder, userParam]
  );

  const endBrowserRecording = useCallback(async () => {
    const active = activeRecorderRef.current;
    if (!active) {
      await fetch(`/api/recording-error?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          recordingId: "unknown",
          error: { message: "No active MediaRecorder" },
        }),
      });
      return;
    }
    setIsSavingRecording(true);
    try {
      const blob = await stopMediaRecorder(active);
      activeRecorderRef.current = null;
      setIsRecording(false);
      await uploadRecordingBlob(active, blob);
    } catch (err) {
      const message = (err as Error).message || "停止录制失败";
      setRecordingError(message);
      await fetch(`/api/recording-error?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          recordingId: active.recordingId,
          error: { message },
        }),
      });
      activeRecorderRef.current = null;
      setIsRecording(false);
    } finally {
      setIsSavingRecording(false);
    }
  }, [uploadRecordingBlob, userParam]);

  const handleManualStart = useCallback(async () => {
    if (isStartingRecording || isSavingRecording || isRecording) return;
    setRecordingError(null);
    setIsStartingRecording(true);
    try {
      // Claim id on server (no SSE wait), then start MediaRecorder in this tab.
      // Avoids the old deadlock: HTTP waiting for the same tab's SSE handler.
      const res = await fetch(`/api/recording-manual-start?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ maxSeconds: 60, withAudio: true }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "手动开始录制失败");
      await beginBrowserRecording(data.recordingId, data.withAudio !== false);
    } catch (err) {
      setRecordingError((err as Error).message);
    } finally {
      setIsStartingRecording(false);
    }
  }, [
    beginBrowserRecording,
    isRecording,
    isSavingRecording,
    isStartingRecording,
    userParam,
  ]);

  const handleManualStop = useCallback(async () => {
    setRecordingError(null);
    try {
      // Prefer local stop + upload (works without Agent / without SSE round-trip)
      if (activeRecorderRef.current) {
        await endBrowserRecording();
        return;
      }
      // Fallback: Agent-started recording — ask server to push stop via SSE
      const res = await fetch(`/api/recording-stop?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "手动停止录制失败");
      if (data.path) setLastRecordingPath(data.path);
    } catch (err) {
      setRecordingError((err as Error).message);
    }
  }, [endBrowserRecording, userParam]);

  const handleManualReset = useCallback(async () => {
    setRecordingError(null);
    discardLocalRecorder();
    try {
      const res = await fetch(`/api/recording-reset?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "重置失败");
    } catch (err) {
      setRecordingError((err as Error).message);
    }
  }, [discardLocalRecorder, userParam]);

  useEffect(() => {
    if (!isRecording) return;
    const timer = setInterval(() => {
      const started = activeRecorderRef.current?.startedAt;
      if (started) setRecordingElapsed((Date.now() - started) / 1000);
    }, 250);
    return () => clearInterval(timer);
  }, [isRecording]);

  const toggleFreeze = () => {
    console.log("toggleFreeze called, current frozenFrame:", frozenFrame);
    if (frozenFrame) {
      console.log("Unfreezing frame");
      setFrozenFrame(null);
    } else if (webcamInstance) {
      console.log("Freezing new frame");
      const screenshot = webcamInstance.getScreenshot();
      if (screenshot) {
        console.log("New frame captured successfully");
        setFrozenFrame(screenshot);
      }
    }
  };

  const handleScreenCapture = async () => {
    console.log("Screen capture button clicked");
    try {
      const screenImage = await captureScreen();
      console.log("Got screen image, length:", screenImage.length);

      // Test if we can even get this far
      alert("截屏成功，可在控制台查看详情。");

      if (!clientIdRef.current) {
        console.error("No client ID available");
        return;
      }

      const response = await fetch(`/api/capture-result?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          clientId: clientIdRef.current,
          image: screenImage,
          type: "screen",
        }),
      });

      console.log("Server response:", response.status);
    } catch (error) {
      console.error("Screen capture error:", error);
      alert("截屏失败：" + (error as Error).message);
    }
  };

  // New function to handle sampling with callback for auto-update
  const handleSample = async (onComplete?: () => void) => {
    console.log("Sample button clicked");
    setSamplingError(null);
    setSamplingResult(null);
    setIsSampling(true);

    try {
      const imageSrc = getImage();
      if (!imageSrc) {
        throw new Error("Failed to capture image for sampling");
      }

      console.log("Sending image for sampling...");

      // Add timeout to prevent hanging requests
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 30000); // 30 second timeout

      const response = await fetch(`/api/process-sample?user=${encodeURIComponent(userParam)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          image: imageSrc,
          prompt: samplingPrompt,
          sessionId: selectedSessionId,
        }),
        signal: controller.signal,
      }).catch((error) => {
        clearTimeout(timeoutId);
        if (error.name === "AbortError") {
          throw new Error("Request timed out after 30 seconds");
        }
        throw error;
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorData = await response.json();
        throw new Error(errorData.error || "Failed to process sample");
      }

      const data = await response.json();
      console.log("Sampling response:", data);

      if (data.success && data.result && data.result.content?.type === "text") {
        setSamplingResult(data.result.content.text);
        // Call the completion callback on success
        if (onComplete) {
          onComplete();
        }
      } else {
        throw new Error("Invalid sampling result format");
      }
    } catch (error) {
      console.error("Sampling error:", error);
      setSamplingError((error as Error).message || "An unknown error occurred");
    } finally {
      setIsSampling(false);
    }
  };

  // Fetch configuration on mount
  useEffect(() => {
    const fetchConfig = async () => {
      try {
        const response = await fetch('/api/config');
        const configData = await response.json();
        setConfig(configData);
      } catch (error) {
        console.error('Error fetching config:', error);
      }
    };

    fetchConfig();
  }, []);

  useEffect(() => {
    const getDevices = async () => {
      try {
        const devices = await navigator.mediaDevices.enumerateDevices();
        const videoDevices = devices.filter(
          (device) => device.kind === "videoinput"
        );
        setDevices(videoDevices);
        setSelectedDevice("default");
      } catch (error) {
        console.error("Error getting devices:", error);
      }
    };

    getDevices();
    navigator.mediaDevices.addEventListener("devicechange", getDevices);
    return () => {
      navigator.mediaDevices.removeEventListener("devicechange", getDevices);
    };
  }, []);

  // Keep SSE handlers on refs so the EventSource is not torn down on every render
  const getImageRef = useRef(getImage);
  const beginBrowserRecordingRef = useRef(beginBrowserRecording);
  const endBrowserRecordingRef = useRef(endBrowserRecording);
  const discardLocalRecorderRef = useRef(discardLocalRecorder);
  useEffect(() => {
    getImageRef.current = getImage;
    beginBrowserRecordingRef.current = beginBrowserRecording;
    endBrowserRecordingRef.current = endBrowserRecording;
    discardLocalRecorderRef.current = discardLocalRecorder;
  }, [getImage, beginBrowserRecording, endBrowserRecording, discardLocalRecorder]);

  useEffect(() => {
    const eventSource = new EventSource(`/api/events?user=${encodeURIComponent(userParam)}`);

    eventSource.onmessage = async (event) => {
      try {
        const data = JSON.parse(event.data);

        switch (data.type) {
          case "connected":
            clientIdRef.current = data.clientId;
            setClientId(data.clientId);
            break;

          case "capture": {
            if (!webcamRef.current || !clientIdRef.current) {
              const error = !webcamRef.current
                ? "摄像头未就绪"
                : "客户端未连接";
              await fetch(`/api/capture-error?user=${encodeURIComponent(userParam)}`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                  clientId: clientIdRef.current,
                  error: { message: error },
                }),
              });
              return;
            }

            const imageSrc = getImageRef.current();
            if (!imageSrc) {
              await fetch(`/api/capture-error?user=${encodeURIComponent(userParam)}`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                  clientId: clientIdRef.current,
                  error: { message: "截取画面失败" },
                }),
              });
              return;
            }

            await fetch(`/api/capture-result?user=${encodeURIComponent(userParam)}`, {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                clientId: clientIdRef.current,
                image: imageSrc,
              }),
            });
            break;
          }

          case "screenshot":
            if (!clientIdRef.current) return;
            try {
              const screenImage = await captureScreen();
              await fetch(`/api/capture-result?user=${encodeURIComponent(userParam)}`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                  clientId: clientIdRef.current,
                  image: screenImage,
                  type: "screen",
                }),
              });
            } catch (error) {
              await fetch(`/api/capture-error?user=${encodeURIComponent(userParam)}`, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                  clientId: clientIdRef.current,
                  error: {
                    message:
                      (error as Error).message || "截屏失败",
                  },
                }),
              });
            }
            break;

          case "start_recording":
            // Agent path — ignore if this tab already has a local recorder (manual start)
            if (activeRecorderRef.current) break;
            await beginBrowserRecordingRef.current(
              data.recordingId,
              data.withAudio !== false
            );
            break;

          case "stop_recording":
            await endBrowserRecordingRef.current();
            break;

          case "recording_reset":
            discardLocalRecorderRef.current();
            setRecordingError(null);
            break;

          case "sample":
            break;

          default:
            break;
        }
      } catch (error) {
        console.error("Error processing message:", error, "Raw message:", event.data);
      }
    };

    return () => {
      eventSource.close();
    };
  }, [userParam]);

  // Handle auto-update with recursive timeout after successful requests
  useEffect(() => {
    console.log("Auto-update effect running:", { 
      autoUpdate, 
      updateInterval, 
      hasSampling: selectedSession?.capabilities.sampling,
      sessionId: selectedSession?.id 
    });
    
    // Clear any existing timer first
    if (autoUpdateIntervalRef.current) {
      clearTimeout(autoUpdateIntervalRef.current);
      autoUpdateIntervalRef.current = null;
    }

    // Recursive function to handle auto-update
    const scheduleNextUpdate = () => {
      // Ensure minimum 5 seconds between requests
      const delayMs = Math.max(updateInterval * 1000, 5000);
      
      autoUpdateIntervalRef.current = setTimeout(() => {
        if (autoUpdate === true && selectedSession?.capabilities.sampling) {
          console.log("Auto-update triggered after", delayMs, "ms");
          handleSample(() => {
            // On successful completion, schedule the next update
            if (autoUpdate === true) {
              scheduleNextUpdate();
            }
          });
        }
      }, delayMs);
    };

    // Only start auto-update if explicitly enabled by user
    if (autoUpdate === true && updateInterval > 0 && selectedSession?.capabilities.sampling) {
      console.log("Starting auto-update");
      // Initial sample when auto-update is enabled
      handleSample(() => {
        // Schedule next update after successful initial sample
        if (autoUpdate === true) {
          scheduleNextUpdate();
        }
      });
    }

    // Cleanup function
    return () => {
      if (autoUpdateIntervalRef.current) {
        console.log("Cleaning up auto-update timer");
        clearTimeout(autoUpdateIntervalRef.current);
        autoUpdateIntervalRef.current = null;
      }
    };
  }, [autoUpdate, updateInterval, selectedSession?.id]); // Only depend on session ID, not the whole object

  // State for all sessions count
  const [totalSessions, setTotalSessions] = useState<number>(0);

  // Poll for active sessions
  useEffect(() => {
    const fetchSessions = async () => {
      try {
        // Fetch sessions for current user
        const response = await fetch(`/api/sessions?user=${encodeURIComponent(userParam)}`);
        if (response.ok) {
          const data = await response.json();
          setSessions(data.sessions);

          // Auto-select the most recent session if none selected
          if (!selectedSessionId && data.sessions.length > 0) {
            // Sort by connection time and select the most recent
            const sortedSessions = [...data.sessions].sort(
              (a, b) =>
                new Date(b.connectedAt).getTime() -
                new Date(a.connectedAt).getTime()
            );
            setSelectedSessionId(sortedSessions[0].id);
          }

          // Clean up selected session if it's no longer available
          if (
            selectedSessionId &&
            !data.sessions.find((s: Session) => s.id === selectedSessionId)
          ) {
            setSelectedSessionId(null);
          }
        }

        // Fetch total sessions count (only if showing banner)
        if (showBanner) {
          const totalResponse = await fetch(`/api/sessions?all=true`);
          if (totalResponse.ok) {
            const totalData = await totalResponse.json();
            setTotalSessions(totalData.sessions.length);
          }
        }
      } catch (error) {
        console.error("Error fetching sessions:", error);
      }
    };

    // Initial fetch
    fetchSessions();

    // Poll every 2 seconds
    sessionPollIntervalRef.current = setInterval(fetchSessions, 2000);

    return () => {
      if (sessionPollIntervalRef.current) {
        clearInterval(sessionPollIntervalRef.current);
      }
    };
  }, [selectedSessionId, userParam, showBanner]);

  return (
    <div>
      {showBanner && (
        <>
          {/* Fixed position connection badge in top right corner */}
          <div className="fixed top-2 right-2 sm:top-4 sm:right-4 z-50 flex items-center gap-1 bg-white dark:bg-slate-800 rounded-md border px-2 py-1 shadow-lg">
            <Users className="h-3 w-3 text-green-600" />
            <span className="text-xs font-medium text-slate-700 dark:text-slate-300">
              {sessions.length}/{totalSessions}
            </span>
          </div>

          {/* Main banner content */}
          <div className="border-b bg-slate-50 dark:bg-slate-900/50">
            <div className="w-full px-3 sm:px-6 py-3">
              <div className="flex flex-col sm:flex-row sm:items-center gap-3 sm:gap-6">
                <div className="flex items-center gap-2">
                  <Info className="h-4 w-4 text-blue-600" />
                  <span className="text-sm font-medium">当前用户</span>
                  <Badge variant="default" className="bg-blue-600 hover:bg-blue-700">
                    {userParam}
                  </Badge>
                </div>

                {/* MCP URL - stacks on mobile */}
                <div className="flex flex-col sm:flex-row sm:items-center gap-2 sm:gap-2 min-w-0 sm:flex-1">
                  <div className="flex items-center gap-2">
                    <Link2 className="h-4 w-4 text-blue-600 flex-shrink-0" />
                    <span className="text-sm font-medium flex-shrink-0">MCP 地址：</span>
                  </div>
                  <div className="flex items-center gap-2 min-w-0 flex-1">
                    <code className="text-xs font-mono bg-slate-100 dark:bg-slate-900 px-2 py-1 rounded border select-all truncate flex-1 text-slate-700 dark:text-slate-300">
                      {config?.mcpHost || window.location.origin}/mcp{config?.mcpHostConfigured && userParam !== 'default' ? `?user=${userParam}` : ''}
                    </code>
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => copyToClipboard(`${config?.mcpHost || window.location.origin}/mcp${config?.mcpHostConfigured && userParam !== 'default' ? `?user=${userParam}` : ''}`)}
                      className="h-7 px-2 flex-shrink-0"
                    >
                      {copied ? (
                        <Check className="h-3 w-3" />
                      ) : (
                        <Copy className="h-3 w-3" />
                      )}
                    </Button>
                  </div>
                </div>
              </div>

              {/* Helper text */}
              <div className="mt-2 text-xs text-muted-foreground">
                在地址后加 <code className="bg-muted px-1 py-0.5 rounded font-mono text-xs">?user=你的ID</code> 可切换用户
              </div>
            </div>
          </div>
        </>
      )}
      <Card className={`w-full max-w-2xl mx-auto ${showBanner ? 'mt-4' : ''}`}>
        <CardHeader>
          <div className="relative">
            <a
              href="https://github.com/Glidema/mcpCut/tree/main/mcp-webcam"
              target="_blank"
              rel="noopener noreferrer"
              className="absolute left-0 top-0 flex items-center gap-2 text-xs sm:text-sm text-muted-foreground hover:text-foreground transition-colors"
            >
              <Github className="h-3 w-3 sm:h-4 sm:w-4" />
              <span className="hidden sm:inline">github.com/Glidema/mcpCut</span>
            </a>
            <CardTitle className="text-lg sm:text-xl font-bold text-center pt-6 sm:pt-0">
              mcp-webcam 摄像头录制
            </CardTitle>
            <p className="text-center text-xs sm:text-sm text-muted-foreground mt-2">
              支持手动点「开始/停止录制」，也支持在 Cursor 里指挥 Agent 调用 MCP
            </p>
          </div>
          <div className="w-full max-w-2xl mx-auto mt-4 space-y-2">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {/* Camera selector */}
              <div className="space-y-2">
                <label className="text-sm font-medium">摄像头</label>
                <Select
                  value={selectedDevice}
                  onValueChange={setSelectedDevice}
                >
                  <SelectTrigger className="w-full">
                    <SelectValue placeholder="选择摄像头" />
                  </SelectTrigger>
                  <SelectContent>
                    <SelectItem value="default">默认摄像头</SelectItem>
                    {devices.map((device) => {
                      const deviceId =
                        device.deviceId || `device-${devices.indexOf(device)}`;
                      return (
                        <SelectItem key={deviceId} value={deviceId}>
                          {device.label ||
                            `摄像头 ${devices.indexOf(device) + 1}`}
                        </SelectItem>
                      );
                    })}
                  </SelectContent>
                </Select>
              </div>

              {/* Session selector - always visible */}
              <div className="space-y-2">
                <label className="text-sm font-medium">
                  {userParam === 'default' ? 'MCP 会话' : `MCP 会话（${userParam}）`}
                </label>
                <Select
                  value={selectedSessionId || ""}
                  onValueChange={setSelectedSessionId}
                  disabled={sessions.length === 0}
                >
                  <SelectTrigger className="w-full">
                    <SelectValue
                      placeholder={
                        sessions.length === 0
                          ? "暂无连接"
                          : "选择 MCP 会话"
                      }
                    />
                  </SelectTrigger>
                  <SelectContent>
                    {sessions.length === 0 ? (
                      <div className="p-2 text-center text-muted-foreground text-sm">
                        暂无 MCP 连接，请在 Cursor 中启用 mcp-webcam
                      </div>
                    ) : (
                      sessions.map((session) => {
                        const connectedTime = new Date(session.connectedAt);
                        const timeString = connectedTime.toLocaleTimeString();

                        // Determine color based on status
                        let colorClass = "bg-red-500"; // Default: stale
                        if (!session.isStale) {
                          if (session.capabilities.sampling) {
                            colorClass = "bg-green-500"; // Active with sampling
                          } else {
                            colorClass = "bg-amber-500"; // Active without sampling
                          }
                        }

                        return (
                          <SelectItem key={session.id} value={session.id}>
                            <div className="flex items-center gap-2">
                              <div
                                className={`w-2 h-2 rounded-full ${colorClass}`}
                              />
                              <span>
                                {session.clientInfo
                                  ? `${session.clientInfo.name} v${session.clientInfo.version}`
                                  : `会话 ${session.id.slice(0, 8)}`}
                              </span>
                              <span className="text-xs text-muted-foreground">
                                ({timeString})
                              </span>
                            </div>
                          </SelectItem>
                        );
                      })
                    )}
                  </SelectContent>
                </Select>
              </div>
            </div>
            {sessions.length > 0 && (
              <div className="text-xs text-muted-foreground text-center">
                <span className="inline-flex items-center gap-1">
                  <div className="w-2 h-2 rounded-full bg-green-500" /> 在线（支持采样）
                </span>
                <span className="inline-flex items-center gap-1 ml-3">
                  <div className="w-2 h-2 rounded-full bg-amber-500" /> 在线（无采样）
                </span>
                <span className="inline-flex items-center gap-1 ml-3">
                  <div className="w-2 h-2 rounded-full bg-red-500" /> 连接失效
                </span>
              </div>
            )}
          </div>
        </CardHeader>
        <CardContent className="px-3 sm:px-6 pt-3 pb-6">
          <div className="rounded-lg overflow-hidden border border-border relative">
            <Webcam
              ref={(webcam) => setWebcam(webcam)}
              audio={true}
              muted={true}
              screenshotFormat="image/jpeg"
              className="w-full"
              videoConstraints={{
                width: 1280,
                height: 720,
                ...(selectedDevice !== "default"
                  ? { deviceId: selectedDevice }
                  : { facingMode: "user" }),
              }}
            />
            {frozenFrame && (
              <img
                src={frozenFrame}
                alt="冻结画面"
                className="absolute inset-0 w-full h-full object-cover"
              />
            )}
            {(isRecording || isSavingRecording) && (
              <div className="absolute top-4 left-4 flex items-center gap-2 rounded-md bg-black/70 px-3 py-1.5 text-sm text-white">
                <Circle
                  className={`h-3 w-3 fill-red-500 text-red-500 ${isRecording ? "animate-pulse" : ""}`}
                />
                <span>
                  {isSavingRecording
                    ? "保存中…"
                    : `录制中 ${recordingElapsed.toFixed(1)} 秒`}
                </span>
              </div>
            )}
            <div className="absolute top-4 right-4">
              <Button
                onClick={toggleFreeze}
                variant={frozenFrame ? "destructive" : "outline"}
                size="sm"
                disabled={isRecording}
              >
                {frozenFrame ? "取消冻结" : "冻结画面"}
              </Button>
            </div>
          </div>
        </CardContent>
        <CardFooter className="flex flex-col gap-4 pb-6">
          <div className="w-full space-y-4">
            <div className="flex flex-col sm:flex-row gap-2 items-stretch sm:items-center">
              <Button
                onClick={handleManualStart}
                disabled={isRecording || isSavingRecording || isStartingRecording}
                variant="default"
                className="w-full sm:w-auto"
              >
                {isStartingRecording ? "启动中…" : "开始录制"}
              </Button>
              <Button
                onClick={handleManualStop}
                disabled={!isRecording && !isSavingRecording}
                variant="destructive"
                className="w-full sm:w-auto"
              >
                停止录制
              </Button>
              <Button
                onClick={handleManualReset}
                variant="outline"
                className="w-full sm:w-auto"
                title="清除卡住的录制状态"
              >
                重置
              </Button>
              {lastRecordingPath && (
                <span className="text-xs text-muted-foreground truncate flex-1" title={lastRecordingPath}>
                  最近文件：{lastRecordingPath}
                </span>
              )}
            </div>
            {recordingError && (
              <Alert variant="destructive">
                <AlertTitle>录制出错</AlertTitle>
                <AlertDescription>{recordingError}</AlertDescription>
              </Alert>
            )}
            {selectedSession && !selectedSession.capabilities.sampling && (
              <Alert className="mb-4">
                <AlertDescription>
                  当前 MCP 会话不支持采样（画面问答）。录制与截图仍可正常使用；若只需录制可忽略本提示。
                </AlertDescription>
              </Alert>
            )}
            <div className="flex flex-col sm:flex-row gap-2">
              <Input
                type="text"
                value={samplingPrompt}
                onChange={(e) => setSamplingPrompt(e.target.value)}
                placeholder="向 Agent 提问画面内容…"
                className="flex-1"
              />
              <Button
                onClick={() => handleSample()}
                variant="default"
                disabled={
                  isSampling ||
                  autoUpdate ||
                  !selectedSession?.capabilities.sampling
                }
                title={
                  !selectedSession?.capabilities.sampling
                    ? "当前会话不支持采样"
                    : ""
                }
                className="w-full sm:w-auto"
              >
                {isSampling ? "分析中…" : "采样提问"}
              </Button>
            </div>


            {/* Sampling results display - always visible */}
            <div className="mt-4 min-h-[80px]">
              {samplingResult && (
                <Alert>
                  <AlertTitle>分析结果</AlertTitle>
                  <AlertDescription>{samplingResult}</AlertDescription>
                </Alert>
              )}

              {samplingError && (
                <Alert variant="destructive">
                  <AlertTitle>采样出错</AlertTitle>
                  <AlertDescription>{samplingError}</AlertDescription>
                </Alert>
              )}

              {!samplingResult && !samplingError && !isSampling && (
                <div className="text-center text-muted-foreground text-sm p-4 border rounded-lg">
                  采样结果会显示在这里（可选功能）
                </div>
              )}

              {isSampling && (
                <div className="text-center text-muted-foreground text-sm p-4 border rounded-lg">
                  正在分析画面…
                </div>
              )}
            </div>

            {/* Auto-update and Screen Capture controls */}
            <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 mt-4">
              <div className="flex flex-col sm:flex-row sm:items-center gap-3 sm:gap-4">
                <div className="flex items-center space-x-2">
                  <Checkbox
                    id="auto-update"
                    checked={autoUpdate}
                    onCheckedChange={(checked) =>
                      setAutoUpdate(checked as boolean)
                    }
                    disabled={!selectedSession?.capabilities.sampling}
                  />
                  <label
                    htmlFor="auto-update"
                    className="text-sm font-medium leading-none peer-disabled:cursor-not-allowed peer-disabled:opacity-70"
                  >
                    自动刷新
                  </label>
                </div>
                <div className="flex items-center gap-2">
                  <Input
                    type="number"
                    value={updateInterval}
                    onChange={(e) =>
                      setUpdateInterval(parseInt(e.target.value) || 30)
                    }
                    className="w-20"
                    min="1"
                    disabled={
                      !autoUpdate || !selectedSession?.capabilities.sampling
                    }
                  />
                  <span className="text-sm text-muted-foreground">秒</span>
                </div>
              </div>
              <Button onClick={handleScreenCapture} variant="secondary" className="w-full sm:w-auto">
                测试截屏
              </Button>
            </div>
          </div>
        </CardFooter>
      </Card>
    </div>
  );
}
